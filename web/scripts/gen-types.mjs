// Regenerate src/api/types.gen.ts.
// Source: live http://localhost:8000/openapi.json, else ../contracts/schema/*.json.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const OPENAPI = process.env.OPENAPI_URL ?? "http://localhost:8000/openapi.json";
const defs = {};
let source;

try {
  const res = await fetch(OPENAPI, { signal: AbortSignal.timeout(3000) });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const text = (await res.text()).replaceAll("#/components/schemas/", "#/$defs/");
  Object.assign(defs, JSON.parse(text).components?.schemas ?? {});
  source = OPENAPI;
} catch (e) {
  console.warn(`openapi unavailable (${e.message}); using contracts/schema`);
}

// The SSE payloads never appear in OpenAPI, so contracts/schema is always merged in.
const dir = new URL("../../contracts/schema/", import.meta.url);
for (const f of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
  const s = JSON.parse(readFileSync(new URL(f, dir), "utf8"));
  for (const [k, v] of Object.entries(s.$defs ?? {})) defs[k] ??= v;
  const name = f.replace(/\.json$/, "").replace(/(^|_)(\w)/g, (_, __, c) => c.toUpperCase());
  const { $defs, ...own } = s;
  defs[name] ??= own;
}
source = source ? `${source} + contracts/schema` : "contracts/schema";

for (const [k, v] of Object.entries(defs)) v.title = k;
const root = {
  title: "Api",
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(Object.keys(defs).map((k) => [k, { $ref: `#/$defs/${k}` }])),
  $defs: defs,
};
const ts = await compile(root, "Api", {
  bannerComment: `/* Generated by scripts/gen-types.mjs from ${source}. Do not edit. */`,
  additionalProperties: false,
  unreachableDefinitions: true,
});
mkdirSync(new URL("../src/api/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/api/types.gen.ts", import.meta.url), ts);
console.log(`types from ${source}: ${Object.keys(defs).length} schemas`);
